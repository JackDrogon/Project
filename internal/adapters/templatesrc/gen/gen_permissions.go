//go:build ignore

package main

import (
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	// Get current working directory (should be internal/adapters/templatesrc)
	cwd, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("failed to get working directory: %w", err)
	}

	entries, err := os.ReadDir(cwd)
	if err != nil {
		return fmt.Errorf("failed to read directory: %w", err)
	}

	var templateDirs []string
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		name := entry.Name()
		// Skip gen directory, hidden directories, and common non-template dirs
		if name == "gen" || strings.HasPrefix(name, ".") {
			continue
		}
		templateDirs = append(templateDirs, name)
	}

	if len(templateDirs) == 0 {
		return errors.New("no template directories found")
	}

	permissions := make(map[string]fs.FileMode)
	for _, dir := range templateDirs {
		if err := collectPermissions(dir, permissions); err != nil {
			return fmt.Errorf("failed to collect permissions for %s: %w", dir, err)
		}
	}

	if err := generateFile(permissions); err != nil {
		return fmt.Errorf("failed to generate file: %w", err)
	}

	fmt.Printf("Generated permissions_generated.go with %d entries\n", len(permissions))
	return nil
}

func collectPermissions(root string, permissions map[string]fs.FileMode) error {
	return filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if entry.IsDir() {
			empty, err := isEmptyDir(path)
			if err != nil {
				return fmt.Errorf("failed to check if directory is empty: %w", err)
			}
			if empty {
				return nil
			}
		}

		info, err := entry.Info()
		if err != nil {
			return fmt.Errorf("failed to stat %s: %w", path, err)
		}

		permissions[filepath.ToSlash(path)] = canonicalMode(info)

		return nil
	})
}

// canonicalMode reduces a filesystem mode to the only distinction git records:
// the owner-executable bit.
//
// Recording info.Mode().Perm() verbatim made generation depend on the umask of
// whoever last ran `go generate`, because git materializes a checkout as
// 0666&^umask / 0777&^umask. The committed table had therefore accumulated a
// mix of 0o644, 0o664, 0o755, 0o775 and 0o764 entries from different machines,
// which meant `just generate` was not reproducible and CI's staleness gate
// passed or failed on umask alone. Worse, those arbitrary modes are embedded in
// the binary and chmod'd onto every scaffolded project, so generated files
// inherited group-writable bits that no user asked for.
func canonicalMode(info fs.FileInfo) fs.FileMode {
	const ownerExecutable = 0o100

	if info.IsDir() || info.Mode().Perm()&ownerExecutable != 0 {
		return 0o755
	}

	return 0o644
}

func isEmptyDir(path string) (bool, error) {
	entries, err := os.ReadDir(path)
	if err != nil {
		return false, err
	}

	for _, entry := range entries {
		if !entry.IsDir() {
			return false, nil
		}
		subPath := filepath.Join(path, entry.Name())
		empty, err := isEmptyDir(subPath)
		if err != nil {
			return false, err
		}
		if !empty {
			return false, nil
		}
	}

	return true, nil
}

func generateFile(permissions map[string]fs.FileMode) error {
	// Sort keys for deterministic output
	keys := slices.Sorted(maps.Keys(permissions))

	var sb strings.Builder
	sb.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	sb.WriteString("package templatesrc\n\n")
	sb.WriteString("import \"io/fs\"\n\n")
	sb.WriteString("var templateModeMetadata = map[string]fs.FileMode{\n")

	for _, key := range keys {
		mode := permissions[key]
		fmt.Fprintf(&sb, "\t%q: 0o%03o,\n", key, mode)
	}

	sb.WriteString("}\n")

	formatted, err := format.Source([]byte(sb.String()))
	if err != nil {
		return fmt.Errorf("failed to format generated code: %w", err)
	}

	outputPath := "permissions_generated.go"
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		return fmt.Errorf("failed to write output file: %w", err)
	}

	return nil
}
